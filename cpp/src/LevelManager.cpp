int LevelManager::getLevelCount() const {
    return static_cast<int>(levels.size());
}

bool LevelManager::isValidLevel(int levelId) const {
    return levelId >= 1 && levelId <= getLevelCount();
}

const LevelDefinition& LevelManager::getLevel(int levelId) const {
    if (!isValidLevel(levelId)) {
        throw std::out_of_range("Invalid Level ID: " + std::to_string(levelId));
    }
    return levels[levelId - 1];
}

const std::vector<LevelDefinition>& LevelManager::getAllLevels() const {
    return levels;
}

bool LevelManager::isLevelUnlocked(int levelId) const {
    if (!isValidLevel(levelId)) return false;
    return unlockedLevels[levelId - 1];
}

bool LevelManager::isLevelCompleted(int levelId) const {
    if (!isValidLevel(levelId)) return false;
    return completedLevels[levelId - 1];
}

bool LevelManager::completeLevel(int levelId) {
    if (!isValidLevel(levelId)) return false;
    completedLevels[levelId - 1] = true;
    if (levelId < getLevelCount()) {
        unlockedLevels[levelId] = true; // Unlock next level
    }
    return true;
}
