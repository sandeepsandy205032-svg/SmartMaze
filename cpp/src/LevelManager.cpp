LevelManager::LevelManager() {
    initializeFixedLevels();
    resetProgression();
}

void LevelManager::resetProgression() {
    int count = getLevelCount();
    unlockedLevels.assign(count, false);
    completedLevels.assign(count, false);

    // Level 01 is initially unlocked
    if (count > 0) {
        unlockedLevels[0] = true;
    }
}

